// Check parity
function checkParity(base, target, path = '') {
  for (const key of Object.keys(base)) {
    const currentPath = path ? `${path}.${key}` : key;
    if (!(key in target)) {
      throw new Error(`Missing key "${currentPath}" in target locale!`);
    }
    if (typeof base[key] === 'object' && !Array.isArray(base[key]) && base[key] !== null) {
      if (typeof target[key] !== 'object') {
        throw new Error(`Type mismatch at "${currentPath}"!`);
      }
      checkParity(base[key], target[key], currentPath);
    }
  }
}

